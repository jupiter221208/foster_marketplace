import React, { useEffect, useState } from 'react'

// next components
import Head from 'next/head'
import Image from 'next/image'

// components
import SecondaryLayout from 'components/Layout/SecondaryLayout'
import Tab from 'components/Tab'
import OutlineButton from 'components/Button/OutlineButton'

import ArtworksSection from 'components/pages/Stats/ArtworksSection'
import CollectionsSection from 'components/pages/Stats/CollectionsSection'
import CreatorsSection from 'components/pages/Stats/CreatorsSection'
import CollectorsSection from 'components/pages/Stats/CollectorsSection'
import MarketplaceSection from 'components/pages/Stats/MarketplaceSection'

// custom functions
import { useViewport } from 'utils'

// images and icons
import EllipseGreen from 'assets/icons/ellipse-green.svg'
import EllipseGreenLight from 'assets/icons/ellipse-green-light.svg'

// json
import TabList from 'assets/json/stats/tab-list.json'

// styles
import styles from './index.module.scss'
import StatsPreviewModal from 'components/Modal/StatsPreviewModal'
import HouseStatsTab from 'components/Tab/HouseStatsTab'
import { useSelector } from 'react-redux'

const Stats = () => {
  const viewport = useViewport()

  const [activeTab, setActiveTab] = useState<any>(0)
  const [tabList, setTabList] = useState<any[]>(TabList)
  const [previewMode, setPreviewMode] = useState(false)
  const [comingSoon, setComingSoon] = useState(false)

  useEffect(() => {
    let array: any[] = []
    TabList.map(item => {
      let object: any = item
      if (item.id === activeTab) {
        object.selected = true
      } else {
        object.selected = false
      }
      array.push(object)
    })
    setTabList(array)
  }, [activeTab])

  const handleSelectedTab = item => {
    if (item.id === 0) setActiveTab(item.id)
  }

  return (
    <div className="g-container">
      <Head>
        <title>House Stats</title>
        <meta name="description" content="Generated by create next app" />
        <link rel="icon" href="/logo.png" />
      </Head>
      <div className={styles.container}>
        <div className={styles.topLeftEllipse}>
          <svg xmlns="http://www.w3.org/2000/svg" width="2321" height="2321" viewBox="0 0 2321 2321">
            <defs>
              <radialGradient id="radial-gradient" cx="0.5" cy="0.5" r="0.5" gradientUnits="objectBoundingBox">
                <stop offset="0" stop-color="var(--ellipse-svg-1)" stop-opacity="0.404" />
                <stop offset="1" stop-color="var(--ellipse-svg-2)" stop-opacity="0" />
              </radialGradient>
            </defs>
            <circle
              id="Ellipse_4322"
              data-name="Ellipse 4322"
              cx="1010.5"
              cy="1010.5"
              r="1010.5"
              transform="translate(150 150)"
              fill="url(#radial-gradient)"
            />
          </svg>
        </div>
        <div className="w-full flex flex-wrap">
          <div className={`${styles.title} z-10 hidden lg:flex`}>House Stats</div>
          <div className="relative mt-[10px] lg:mt-[84px] w-full h-auto flex relative overflow-hidden  justify-between z-10 h-[62px] lg:h-[90px]">
            <HouseStatsTab
              tabList={tabList}
              onChange={item => {
                if (item.coming_soon === true) {
                  setComingSoon(true)
                  setTimeout(() => {
                    setComingSoon(false)
                  }, 3000)
                } else handleSelectedTab(item)
              }}
            />
            {(viewport === 'xs' || viewport === 'sm' || viewport === 'md') && comingSoon && (
              <div className={styles.tooltip}>This feature is not available but is coming soon.</div>
            )}
          </div>
          <div className="mt-0 lg:mt-8 lg:mt-16 w-full z-10">
            {activeTab === 0 && <ArtworksSection />}
            {/* {activeTab === 1 && <CollectionsSection />}
            {activeTab === 2 && <CreatorsSection />}
            {activeTab === 3 && <CollectorsSection />}
            {activeTab === 4 && <MarketplaceSection />} */}
          </div>
        </div>
      </div>
      <StatsPreviewModal
        open={previewMode}
        close={() => {
          window.history.go(-1)
          setPreviewMode(false)
        }}
      />
    </div>
  )
}

export default Stats

Stats.getLayout = function getLayout(page) {
  return <SecondaryLayout>{page}</SecondaryLayout>
}
