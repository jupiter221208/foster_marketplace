import React, { useEffect, useState } from 'react'

// next components
import Head from 'next/head'
import Image from 'next/image'

// components
import SecondaryLayout from 'components/Layout/SecondaryLayout'
import Tab from 'components/Tab'
import OutlineButton from 'components/Button/OutlineButton'

// images and icons
import EllipseGreen from 'assets/icons/ellipse-green.svg'

// json
import TabList from 'assets/json/stats/tab-list.json'

// styles
import styles from './index.module.scss'

const Stats = props => {
  const [activeTab, setActiveTab] = useState(0)
  const [tabList, setTabList] = useState(TabList)
  useEffect(() => {
    let array = []
    TabList.map(item => {
      let object = item
      if (item.id === activeTab) {
        object.selected = true
      } else {
        object.selected = false
      }
      array.push(object)
    })
    setTabList(array)
  }, [activeTab])

  const handleSelectedTab = item => {
    setActiveTab(item.id)
  }

  return (
    <div className="g-container">
      <Head>
        <title>House Stats</title>
        <meta name="description" content="Generated by create next app" />
        <link rel="icon" href="/logo.svg" />
      </Head>
      <div className={styles.container}>
        <div className={styles.topLeftEllipse}>
          <Image src={EllipseGreen} width={2021} height={2021} alt="" objectFit="cover" />
        </div>
        <div className="w-full flex flex-wrap">
          <div className={styles.title}>House Stats</div>
          <div className="mt-[84px] w-full flex justify-between z-10">
            <Tab tabList={tabList} onChange={item => handleSelectedTab(item)} />
            <OutlineButton label="See All" onClick={() => {}} borderColor="#ffffff" height="42px" />
          </div>
        </div>
      </div>
    </div>
  )
}

export default Stats

Stats.getLayout = function getLayout(page) {
  return <SecondaryLayout>{page}</SecondaryLayout>
}
