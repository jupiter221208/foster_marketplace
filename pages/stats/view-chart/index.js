import React, { useEffect, useState } from 'react'

// next components
import Head from 'next/head'
import Image from 'next/image'
import { useRouter } from 'next/router'

// components
import SecondaryLayout from 'components/Layout/SecondaryLayout'
import OutlineButton from 'components/Button/OutlineButton'
import GradientButton from 'components/Button/GradientButton'
import Chart from 'components/Chart'
import Radio from 'components/Radio'
import ViewChartSortModal from 'components/Modal/ViewChartSortModal'

// json
import CategoryList from 'assets/json/popular-category.json'
import ChartTotalVolume from 'assets/json/stats/chart-total-volume.json'
import ChartTypeList from 'assets/json/stats/chart-type.json'

// images and icons
import EllipseGreen from 'assets/icons/ellipse-green.svg'
import SortGreenIcon from 'assets/icons/sort-green.svg'

// styles
import styles from './index.module.scss'

const ViewChart = props => {
  const { viewport } = props

  const router = useRouter()
  const id = router.query['id']
  const [category, setCategory] = useState()

  useEffect(() => {
    if (id !== undefined) {
      const result = CategoryList.filter(elem => elem.id === Number(id))
      setCategory(result[0])
    }
  }, [id])

  const [active, setActive] = useState(0)

  const handleChangeActive = value => {
    setActive(value)
  }

  const [selectedChartType, setSelectedChartType] = useState(ChartTypeList[0])

  const [showSortModal, setShowSortModal] = useState(false)

  return (
    <div className="g-container">
      <Head>
        <title>House Stats</title>
        <meta name="description" content="Generated by create next app" />
        <link rel="icon" href="/logo.svg" />
      </Head>
      <div className={styles.container}>
        <div className={styles.topLeftEllipse}>
          <Image src={EllipseGreen} alt="" objectFit="cover" />
        </div>
        <div className="w-full">
          <div className="w-full flex justify-end pt-[50px]">
            <div className="z-10">
              <OutlineButton
                label="Return"
                onClick={() => router.back()}
                borderColor="#EFF0F6"
                borderWidth="2px"
                height={viewport === 'xs' || viewport === 'sm' || viewport === 'md' ? '40px' : '48px'}
                paddingLeft={viewport === 'xs' || viewport === 'sm' || viewport === 'md' ? '25px' : '48px'}
                paddingRight={viewport === 'xs' || viewport === 'sm' || viewport === 'md' ? '25px' : '48px'}
              />
            </div>
          </div>
          <div className="w-full flex flex-wrap justify-center md:justify-between text-center md:text-left items-start pt-[18px] md:pt-[50px]">
            <div className="block z-10">
              <div className={styles.title}>{category?.name}</div>
              <div className={styles.subTitle}>(Total Volume)</div>
            </div>
            <div className="hidden md:flex justify-between gap-[10px] lg:gap-[30px] xl:gap-[50px] z-10">
              <GradientButton
                label="24 hrs"
                onClick={() => handleChangeActive(0)}
                color={active === 0 ? '#202427' : '#979EA2'}
                backgroundColor01={active === 0 ? '#5ac3ba' : 'transparent'}
                backgroundColor02={active === 0 ? '#2D625D' : 'transparent'}
                gradientDirection="bottom"
              />
              <GradientButton
                label="7 days"
                onClick={() => handleChangeActive(1)}
                color={active === 1 ? '#202427' : '#979EA2'}
                backgroundColor01={active === 1 ? '#5ac3ba' : 'transparent'}
                backgroundColor02={active === 1 ? '#2D625D' : 'transparent'}
                gradientDirection="bottom"
              />
              <GradientButton
                label="30 days"
                onClick={() => handleChangeActive(2)}
                color={active === 2 ? '#202427' : '#979EA2'}
                backgroundColor01={active === 2 ? '#5ac3ba' : 'transparent'}
                backgroundColor02={active === 2 ? '#2D625D' : 'transparent'}
                gradientDirection="bottom"
              />
              <GradientButton
                label="All Time"
                onClick={() => handleChangeActive(3)}
                color={active === 3 ? '#202427' : '#979EA2'}
                backgroundColor01={active === 3 ? '#5ac3ba' : 'transparent'}
                backgroundColor02={active === 3 ? '#2D625D' : 'transparent'}
                gradientDirection="bottom"
              />
            </div>
          </div>

          <div className="flex md:hidden w-full mt-[42px]">
            <div className="w-full z-10">
              <OutlineButton
                label="Total Volume"
                onClick={() => setShowSortModal(true)}
                icon={SortGreenIcon}
                fullWidth
                direction="rtl"
                height="48px"
              />
            </div>
          </div>

          <div className="w-full mt-[38px] md:mt-[66px] overflow-hidden z-10">
            <Chart list={ChartTotalVolume} viewport={viewport} />
          </div>
          <div className="w-full hidden md:flex flex-wrap justify-center mt-[140px] mb-[208px] gap-x-8 px-10">
            <Radio data={ChartTypeList} selected={selectedChartType} onChange={item => setSelectedChartType(item)} />
          </div>
          <div className="flex md:hidden w-full justify-between gap-[10px] lg:gap-[30px] xl:gap-[50px] mt-[38px] mb-[200px] z-10">
            <GradientButton
              label="24 hrs"
              onClick={() => handleChangeActive(0)}
              color={active === 0 ? '#202427' : '#979EA2'}
              backgroundColor01={active === 0 ? '#5ac3ba' : 'transparent'}
              backgroundColor02={active === 0 ? '#2D625D' : 'transparent'}
              gradientDirection="bottom"
            />
            <GradientButton
              label="7 days"
              onClick={() => handleChangeActive(1)}
              color={active === 1 ? '#202427' : '#979EA2'}
              backgroundColor01={active === 1 ? '#5ac3ba' : 'transparent'}
              backgroundColor02={active === 1 ? '#2D625D' : 'transparent'}
              gradientDirection="bottom"
            />
            <GradientButton
              label="30 days"
              onClick={() => handleChangeActive(2)}
              color={active === 2 ? '#202427' : '#979EA2'}
              backgroundColor01={active === 2 ? '#5ac3ba' : 'transparent'}
              backgroundColor02={active === 2 ? '#2D625D' : 'transparent'}
              gradientDirection="bottom"
            />
            <GradientButton
              label="All Time"
              onClick={() => handleChangeActive(3)}
              color={active === 3 ? '#202427' : '#979EA2'}
              backgroundColor01={active === 3 ? '#5ac3ba' : 'transparent'}
              backgroundColor02={active === 3 ? '#2D625D' : 'transparent'}
              gradientDirection="bottom"
            />
          </div>
        </div>
      </div>
      <ViewChartSortModal
        open={showSortModal}
        data={ChartTypeList}
        selected={selectedChartType}
        onChange={item => setSelectedChartType(item)}
        close={() => setShowSortModal(false)}
      />
    </div>
  )
}

export default ViewChart

ViewChart.getLayout = function getLayout(page) {
  return <SecondaryLayout>{page}</SecondaryLayout>
}
