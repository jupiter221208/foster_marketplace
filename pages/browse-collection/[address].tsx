import React, { useEffect, useState } from 'react'

// next components
import Head from 'next/head'

// components
import PrimaryLayout from 'components/Layout/PrimaryLayout'
import MainSection from 'components/pages/BrowseCollection/MainSection'
import CollectionSection from 'components/pages/BrowseCollection/CollectionSection'

// styles
import styles from './index.module.scss'

// router
import { useRouter } from 'next/router'

// solana
import { getCollectionByAddress } from 'utils/collection.util'

// redux
import { useMetaplex } from 'hooks/useMetaplex'
import { useDispatch, useSelector } from 'react-redux'

const BrowseCollection = () => {
  const router = useRouter()
  const { address } = router.query

  const dispatch = useDispatch()
  const isLoading = useSelector<any>(state => state.isLoading)

  const [collection, setCollection] = useState({})

  const { metaplex: mx } = useMetaplex()

  useEffect(() => {
    if (address !== undefined) {
      const getCollection = async () => {
        dispatch({ type: 'set', isLoading: true })
        const collection = await getCollectionByAddress(mx, address.toString())
        setCollection(collection)
        dispatch({ type: 'set', isLoading: false })
      }
      if (mx && address) getCollection()
    }
  }, [mx, address])

  return (
    <div className="g-container">
      <Head>
        <title>Browse Collection</title>
        <meta name="description" content="Generated by create next app" />
        <link rel="icon" href="/logo.svg" />
      </Head>
      <div className={styles.container}>
        <MainSection collection={collection} />
        {!isLoading && <CollectionSection collection={collection} />}
      </div>
    </div>
  )
}

export default BrowseCollection

BrowseCollection.getLayout = function getLayout(page) {
  return <PrimaryLayout>{page}</PrimaryLayout>
}
