import React, { useEffect, useState } from 'react'

// next components
import { useRouter } from 'next/router'

import Head from 'next/head'
import Image from 'next/image'

// components
import PrimaryLayout from 'components/Layout/PrimaryLayout'
import TrendingCollectionSection from 'components/pages/Home/TrendingCollectionSection'
import MostPopularSection from 'components/pages/Home/MostPopularSection'
import MarketplaceReleaseSection from 'components/pages/Home/MarketplaceReleaseSection'
import LiveAuctionSection from 'components/pages/Home/LiveAuctionSection'
import FreshMintSection from 'components/pages/Home/FreshMintSection'

// images and icons
import CategoryImage from 'assets/images/category.png'

// json
import PopularCategoryList from 'assets/json/popular-category.json'

// styles
import styles from './index.module.scss'
import PopularCategorySection from 'components/pages/Home/PopularCategorySection'

const Category = props => {
  const { viewport } = props
  const router = useRouter()
  const [categoryInfo, setCategoryInfo] = useState('')

  useEffect(() => {
    const cateId = router.query.id
    let category = PopularCategoryList[cateId]
    setCategoryInfo(category)
  }, [])

  return (
    <div className="g-container">
      <Head>
        <title>Foster Marketplace</title>
        <meta name="description" content="Generated by create next app" />
        <link rel="icon" href="/logo.svg" />
      </Head>
      <div className={styles.container}>
        <div className="relative w-full mt-4 lg:mt-8">
          {categoryInfo.type === 'image' ? <Image src={categoryInfo.banner} width={1620} height={460} alt="" /> : <></>}
          {categoryInfo.type === 'video' ? (
            <div className={styles.videoContainer}>
              <video autoPlay loop muted>
                <source type="video/mp4" src={categoryInfo.banner} />
              </video>
            </div>
          ) : (
            <></>
          )}
          {viewport === 'md' || viewport === 'sm' || viewport === 'xs' ? (
            <></>
          ) : (
            <div className={styles.bottomMask}></div>
          )}

          <div className={styles.title}>{categoryInfo.name}</div>
        </div>
        <TrendingCollectionSection viewport={viewport} />
        <MostPopularSection viewport={viewport} />
        <MarketplaceReleaseSection viewport={viewport} />
        <LiveAuctionSection viewport={viewport} />
        <FreshMintSection viewport={viewport} />
        <PopularCategorySection viewport={viewport} type="category" />
      </div>
    </div>
  )
}

export default Category

Category.getLayout = function getLayout(page) {
  return <PrimaryLayout>{page}</PrimaryLayout>
}

export async function getServerSideProps(context) {
  return {
    props: {},
  }
}
