import React, { useEffect, useState } from 'react'

// next components
import Head from 'next/head'
import Image from 'next/image'

// components
import SecondaryLayout from 'components/Layout/SecondaryLayout'
import Tab01 from 'components/Tab/Tab01'
import ProfileSection from 'components/pages/Settings/ProfileSection'
import NotificationSection from 'components/pages/Settings/NotificationSection'
import PermissionAndPrivacySection from 'components/pages/Settings/PermissionAndPrivacySection'
import ReferralSection from 'components/pages/Settings/ReferralSection'
import SecuritySection from 'components/pages/Settings/SecuritySection'
import Alert from 'components/Alert'

// json
import TabList from 'assets/json/settings/tab-list.json'

// images and icons
import EllipseGreen from 'assets/icons/ellipse-green.svg'

// styles
import styles from './index.module.scss'

const Settings = () => {
  const [selectedTab, setSelectedTab] = useState(0)
  const [tabList, setTabList] = useState(TabList)
  const [showAlert, setShowAlert] = useState<boolean>(false)

  useEffect(() => {
    let array: any[] = []
    TabList.map(item => {
      let object: any = item
      if (item.id === selectedTab) {
        object.selected = true
      } else {
        object.selected = false
      }
      array.push(object)
    })
    setTabList(array)
  }, [selectedTab])

  const handleSelectedTab = item => {
    setSelectedTab(item.id)
  }

  const alertData = [
    {
      id: 0,
      title: 'Settings Updated!',
      description: `Your profile settings have been updated successfully`,
      type: 'success',
    },
  ]

  return (
    <div className="g-container">
      <Head>
        <title>Settings</title>
        <meta name="description" content="Generated by create next app" />
        <link rel="icon" href="/logo.svg" />
      </Head>
      <div className={styles.container}>
        <div className={styles.topLeftEllipse}>
          <Image src={EllipseGreen} width={2021} height={2021} alt="" objectFit="cover" />
        </div>
        <div className="w-full flex flex-wrap">
          <div className="w-full flex flex-wrap z-10">
            <div className={`mt-[100px] ${styles.subject}`}>Settings</div>
            {/* <div className="w-full flex lg:hidden justify-center mt-[50px]">
              {selectedTab === 0 && <div className={styles.title}>Profile</div>}
              {selectedTab === 1 && <div className={styles.title}>Notifications</div>}
              {selectedTab === 2 && <div className={styles.title}>Permissions & Privacy</div>}
              {selectedTab === 3 && <div className={styles.title}>Referral Program</div>}
              {selectedTab === 4 && <div className={styles.title}>Security</div>}
            </div> */}
            <div className="w-full mt-8 lg:mt-[50px] overflow-auto">
              <Tab01 tabList={tabList} onChange={item => handleSelectedTab(item)} />
            </div>
            <div className="w-[85%]">
              {selectedTab === 0 && (
                <ProfileSection
                  success={() => {
                    setShowAlert(true)
                  }}
                />
              )}
            </div>
            <div className="w-[85%]">
              {selectedTab === 1 && (
                <NotificationSection
                  success={() => {
                    setShowAlert(true)
                  }}
                />
              )}
            </div>
            <div className="w-full">
              {selectedTab === 2 && (
                <PermissionAndPrivacySection
                  success={() => {
                    setShowAlert(true)
                  }}
                />
              )}
            </div>
            <div className="w-full">
              {selectedTab === 3 && (
                <ReferralSection
                  success={() => {
                    setShowAlert(true)
                  }}
                />
              )}
            </div>
            <div className="w-full">
              {selectedTab === 4 && (
                <SecuritySection
                  success={() => {
                    setShowAlert(true)
                  }}
                />
              )}
            </div>
          </div>
        </div>
      </div>
      <Alert
        open={showAlert}
        close={() => {
          setShowAlert(false)
        }}
        data={alertData}
      />
    </div>
  )
}

export default Settings

Settings.getLayout = function getLayout(page) {
  return <SecondaryLayout>{page}</SecondaryLayout>
}
